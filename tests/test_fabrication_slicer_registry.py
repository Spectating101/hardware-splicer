from __future__ import annotations

import hashlib

import httpx
import pytest

from hardware_splicer.fabrication_operator import FabricationGrantStore, FabricationValidationError
from hardware_splicer.printer_registry import PrinterRegistry
from hardware_splicer.slicer_operator import SlicerOperator, SlicerProfile


GEOMETRY = b"solid hs-test\nendsolid hs-test\n"
PROFILE = b"[print:HS test]\nlayer_height = 0.2\n"
GCODE = b"; generated by fake slicer\nG28\nG1 X1 Y1\n"


class FakeSlicer:
    name = "fake_slicer"
    version = "1.2.3"

    def __init__(self):
        self.calls = []

    def slice(self, *, source_filename, geometry, profile):
        self.calls.append((source_filename, geometry, profile))
        return GCODE, {"estimated_time_seconds": 42, "estimated_material_mm": 123.4}


def _profile():
    return SlicerProfile(
        profile_id="p1-pla-02",
        printer_id="printer-lab",
        filename="profile.ini",
        content=PROFILE,
        material="PLA",
    )


def test_slicer_receipt_binds_geometry_profile_and_exact_gcode():
    runner = FakeSlicer()
    artifact = SlicerOperator(runner).slice_geometry(
        source_filename="field-case.stl",
        geometry=GEOMETRY,
        profile=_profile(),
    )

    receipt = artifact.receipt.to_dict()
    assert artifact.gcode == GCODE
    assert receipt["schema"] == "hardware_splicer.slicer_receipt.v1"
    assert receipt["printer_id"] == "printer-lab"
    assert receipt["profile_id"] == "p1-pla-02"
    assert receipt["source_geometry_sha256"] == hashlib.sha256(GEOMETRY).hexdigest()
    assert receipt["profile_sha256"] == hashlib.sha256(PROFILE).hexdigest()
    assert receipt["output_gcode_sha256"] == hashlib.sha256(GCODE).hexdigest()
    assert receipt["output_size_bytes"] == len(GCODE)
    assert receipt["estimates"]["estimated_time_seconds"] == 42
    assert runner.calls[0][0] == "field-case.stl"


def test_profile_public_descriptor_never_exposes_profile_bytes():
    descriptor = _profile().public_descriptor()
    assert descriptor == {
        "profile_id": "p1-pla-02",
        "printer_id": "printer-lab",
        "material": "PLA",
        "profile_sha256": hashlib.sha256(PROFILE).hexdigest(),
    }
    assert "content" not in descriptor


def test_slicer_rejects_unknown_geometry_type_before_runner_is_called():
    runner = FakeSlicer()
    with pytest.raises(FabricationValidationError, match="unsupported"):
        SlicerOperator(runner).slice_geometry(
            source_filename="case.exe",
            geometry=GEOMETRY,
            profile=_profile(),
        )
    assert runner.calls == []


def test_printer_registry_public_surface_hides_endpoint_and_credentials(tmp_path):
    registry = PrinterRegistry.from_mapping(
        [
            {
                "printer_id": "printer-lab",
                "display_name": "Lab MK4",
                "backend": "octoprint",
                "base_url": "http://printer.internal:5000",
                "headers": {"X-Api-Key": "super-secret"},
            }
        ]
    )
    public = registry.list_public()
    assert public == [
        {
            "printer_id": "printer-lab",
            "display_name": "Lab MK4",
            "backend": "octoprint",
            "capabilities": ["stage", "status", "start", "pause", "resume", "cancel"],
        }
    ]
    rendered = repr(public)
    assert "printer.internal" not in rendered
    assert "super-secret" not in rendered


def test_registry_builds_only_configured_printer_and_transport_uses_server_endpoint(tmp_path):
    seen = []

    def handler(request: httpx.Request) -> httpx.Response:
        seen.append(request)
        return httpx.Response(200, json={})

    client = httpx.Client(transport=httpx.MockTransport(handler))
    registry = PrinterRegistry.from_mapping(
        [
            {
                "printer_id": "printer-lab",
                "backend": "octoprint",
                "base_url": "http://printer.internal:5000",
                "headers": {"X-Api-Key": "super-secret"},
            }
        ]
    )
    printer = registry.build_printer(
        "printer-lab",
        grants=FabricationGrantStore(tmp_path / "grants"),
        client=client,
    )
    observation = printer.status()
    assert observation["physical_correctness"] == "UNPROVEN"
    assert [str(request.url) for request in seen] == [
        "http://printer.internal:5000/api/job",
        "http://printer.internal:5000/api/printer",
    ]
    assert all(request.headers["X-Api-Key"] == "super-secret" for request in seen)
    client.close()


def test_registry_refuses_agent_selected_or_unknown_network_target(tmp_path):
    registry = PrinterRegistry.from_mapping(
        [
            {
                "printer_id": "printer-lab",
                "backend": "moonraker",
                "base_url": "http://moonraker.internal:7125",
            }
        ]
    )
    with pytest.raises(FabricationValidationError, match="unknown configured printer"):
        registry.build_printer(
            "http://attacker.invalid:9999",
            grants=FabricationGrantStore(tmp_path / "grants"),
        )


def test_registry_rejects_duplicate_ids_and_unsupported_backends():
    item = {
        "printer_id": "printer-lab",
        "backend": "octoprint",
        "base_url": "http://printer.internal:5000",
    }
    with pytest.raises(FabricationValidationError, match="duplicate"):
        PrinterRegistry.from_mapping([item, item])
    with pytest.raises(FabricationValidationError, match="unsupported printer backend"):
        PrinterRegistry.from_mapping(
            [
                {
                    "printer_id": "printer-lab",
                    "backend": "arbitrary-http",
                    "base_url": "http://printer.internal:5000",
                }
            ]
        )
