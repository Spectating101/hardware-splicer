#!/usr/bin/env python3
"""Prepare one source-bound, inert Crazyflie app-layer compilation candidate.

Uses a caller-cloned *pinned* Bitcraze firmware checkout; never flashes or
starts motors. This only tests integration of app Kbuild code with the vendor
STM32 flight firmware, not a functional deck driver.
"""
from __future__ import annotations
import argparse
import hashlib
import json
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0,str(ROOT/"src"))
from hardware_splicer.system_example_microdrone import assess_microdrone


def sha(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def prepare(design_path:Path, guidance_path:Path, vendor_dir:Path, out:Path, expected_vendor_sha:str)->dict:
    design=json.loads(design_path.read_text())
    guidance=json.loads(guidance_path.read_text())
    assessed=assess_microdrone(design,guidance_scenario=guidance)
    if assessed["verdict"] != "DESIGN_REVIEW_BLOCKED" or not assessed["preliminary_checks_pass"]:
        raise ValueError("Design preliminary constraints not satisfied")
    vendor_dir=vendor_dir.resolve()
    ref=subprocess.run(["git","-C",str(vendor_dir),"rev-parse","HEAD"],
                       capture_output=True,text=True,check=True).stdout.strip()
    if ref != expected_vendor_sha or len(ref)!=40:
        raise ValueError(f"Vendor firmware revision not pinned: {ref} != {expected_vendor_sha}")
    target=vendor_dir/"examples/hs_sensor_deck"
    if target.exists():
        raise FileExistsError("Vendor checkout already has an HS app; refusing overwrite")
    source=ROOT/"examples/system_examples/microdrone_firmware_app"
    shutil.copytree(source,target)
    design_sha=assessed["source_design_sha256"]
    header=f"""/* AUTOGENERATED for the pinned HS design revision, no flight authority. */
#ifndef HS_SYSTEM_CONTRACT_H
#define HS_SYSTEM_CONTRACT_H
#define HS_SYSTEM_DESIGN_SHA256 "{design_sha}"
#define HS_DECK_MAX_CURRENT_MA 80
#define HS_FLIGHT_AUTHORIZED 0
#endif
"""
    (target/"src/system_contract.h").write_text(header)
    manifest={
       "schema_version":"hardware_splicer.microdrone_firmware_build_input.v1",
       "upstream_repo":"bitcraze/crazyflie-firmware",
       "upstream_commit":ref,
       "design_sha256":design_sha,
       "guidance_sha256":assessed["source_guidance_sha256"],
       "app_sources":{p.relative_to(target).as_posix():sha(p.read_bytes())
                      for p in sorted(target.rglob("*")) if p.is_file()},
       "build_target":"cf2",
       "firmware_extended":True,
       "sensor_deck_driver_implemented":False,
       "flight_firmware_real_hardware_tested":False,
       "motors_start_authorized":False,
       "firmware_flash_authorized":False,
    }
    out.mkdir(parents=True,exist_ok=True)
    path=out/"FIRMWARE_APP_INPUT_RECEIPT.json"
    if path.exists():
        raise FileExistsError("Cannot overwrite an existing firmware receipt")
    path.write_text(json.dumps(manifest,indent=2,sort_keys=True)+"\n")
    return manifest


def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument("--design",type=Path,default=ROOT/"examples/system_examples/microdrone_sensor_deck_001.json")
    p.add_argument("--guidance",type=Path,default=ROOT/"examples/robotics_guidance/crazyflie_custom_sensor_deck.json")
    p.add_argument("--upstream",type=Path,required=True)
    p.add_argument("--commit",required=True)
    p.add_argument("--out",type=Path,required=True)
    args=p.parse_args()
    print(json.dumps(prepare(args.design,args.guidance,args.upstream,args.out,args.commit),indent=2))


if __name__=="__main__":
    main()
