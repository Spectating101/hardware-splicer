"""Build revision B of the ESP32 pan/tilt servo controller board (unrouted).

Revision A (examples/main_ctrl_esp32_servo.kicad_pcb, generated by HS in June 2026) fails
KiCad DRC and, checked against KiCad's own symbol library, is wired to the wrong pins:

* ESP32-WROOM-32 pin 1 is GND but carried +3V3; pin 2 (VDD) carried EN; pin 3 (EN) was open.
* The CP2102 UART sat on pins 22/23 (GPIO.4 / CTS); RXD and TXD are pins 25 and 26
  (KiCad symbol CP2102N-Axx-xQFN28, the CP2102's pin-compatible successor).
* GPIO0 was pulled high with no button or auto-reset, so the board could not enter its bootloader.
* Its footprints were not KiCad library footprints; the USB connector's own pads overlapped.

Revision B keeps the parts, nets and function, uses KiCad library footprints, corrects the pins,
adds BOOT (GPIO0 to GND) and RESET (EN to GND) buttons and an EN delay capacitor, and places the
parts clear of each other. It is written unrouted; route it with HS's routing engine
(scripts/route_board.py) and check it with KiCad DRC. Software evidence only: nothing here has
been fabricated or powered.

Run with a Python that imports pcbnew:
  python3 scripts/build_esp32_servo_rev_b.py UNROUTED.kicad_pcb
  (route it with HS's routing engine, FreeRouting 2.1.0)
  python3 scripts/build_esp32_servo_rev_b.py pour ROUTED.kicad_pcb OUT.kicad_pcb
"""

