def stitch_ground(pcb: str) -> int:
    """Give every ground pad the top pour cannot reach a via to the bottom plane, beside the pad, keeping
    only placements that add no DRC error. Each trial runs in its own process (pcbnew is not stable
    across repeated loads and fills in one process)."""
    import math

    added = 0
    for _ in range(12):
        report = drc(pcb)
        stranded = [(item["pos"]["x"], item["pos"]["y"]) for row in report["unconnected_items"] for item in row["items"]
                    if item["description"].startswith("Pad") and "[GND]" in item["description"]]
        if not stranded and report["unconnected_items"]:
            # DRC names a cut-off piece of pour, not its pad: find the ground pads in via-less pieces.
            done = subprocess.run([sys.executable, __file__, "stranded", pcb], capture_output=True, text=True, check=False)
            stranded = [tuple(point) for point in json.loads(done.stdout.strip().splitlines()[-1] or "[]")]
        if not stranded:
            break
        baseline = sum(1 for row in report["violations"] if row["severity"] == "error")
        x, y = stranded[0]
        trial = pcb + ".trial.kicad_pcb"
        placed = False
        for radius in (0.9, 1.2, 1.6, 2.0):
            for step in range(16):
                angle = 2 * math.pi * step / 16
                vx, vy = round(x + radius * math.cos(angle), 4), round(y + radius * math.sin(angle), 4)
                _step("trialvia", pcb, str(x), str(y), str(vx), str(vy), trial)
                result = drc(trial)
                errors = sum(1 for row in result["violations"] if row["severity"] == "error")
                still = (len(result["unconnected_items"]) >= len(report["unconnected_items"])
                         or any(abs(item["pos"]["x"] - x) < 1e-3 and abs(item["pos"]["y"] - y) < 1e-3
                                for row in result["unconnected_items"] for item in row["items"]))
                if errors <= baseline and not still:
                    shutil.move(trial, pcb)
                    added += 1
                    placed = True
                    break
            if placed:
                break
        for suffix in (".trial.kicad_pcb", ".trial.kicad_pro", ".trial.kicad_prl"):
            Path(pcb + suffix).unlink(missing_ok=True)
        if not placed:
            break
    return added


def _step(*args: str) -> None:
    """Run one pcbnew step of this script in a fresh process."""
    done = subprocess.run([sys.executable, __file__, *args], capture_output=True, text=True, check=False)
    if done.returncode != 0:
        raise SystemExit(f"step {args[0]} failed ({done.returncode}): {done.stderr[-1500:]}")


def build_all(out: str) -> dict:
    with tempfile.TemporaryDirectory(prefix="hs-revb-") as work:
        unrouted, routed = f"{work}/unrouted.kicad_pcb", f"{work}/routed.kicad_pcb"
        _step("build", unrouted)
        _step("ground", unrouted, "off")
        stats = route(unrouted, routed)
        shutil.copy(routed, out)
    _step("ground", out, "on")
    widen(out)
    _step("pour", out)
    _step("stitchplanes", out)
    _step("dropvias", out)
    stitched = stitch_ground(out)
    removed = remove_dangling(out)
    settle(out)
    report = drc(out)
    summary = {"route": stats, "ground_stitch_vias": stitched, "dangling_removed": removed,
               "drc_errors": sum(1 for row in report["violations"] if row["severity"] == "error"),
               "drc_warnings": sum(1 for row in report["violations"] if row["severity"] == "warning"),
               "unconnected": len(report["unconnected_items"])}
    print(json.dumps(summary))
    return summary


