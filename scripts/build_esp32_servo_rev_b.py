def build(out: str) -> None:
    board = pcbnew.BOARD()
    settings = board.GetDesignSettings()
    settings.SetBoardThickness(pcbnew.FromMM(1.6))
    # The ESP32-WROOM-32 library footprint's thermal vias are 0.2 mm drills; state that as the
    # board's minimum (a common fab capability) rather than drop the vias.
    settings.m_MinThroughDrill = pcbnew.FromMM(0.2)
    corners = [(0, 0), (80, 0), (80, 50), (0, 50)]
    for (x0, y0), (x1, y1) in zip(corners, corners[1:] + corners[:1]):
        edge = pcbnew.PCB_SHAPE(board)
        edge.SetShape(pcbnew.SHAPE_T_SEGMENT)
        edge.SetStart(pcbnew.VECTOR2I_MM(x0, y0))
        edge.SetEnd(pcbnew.VECTOR2I_MM(x1, y1))
        edge.SetLayer(pcbnew.Edge_Cuts)
        edge.SetWidth(pcbnew.FromMM(0.15))
        board.Add(edge)

    nets = {}
    for _, _, _, _, _, pads in PARTS.values():
        for name in pads.values():
            if name not in nets:
                nets[name] = pcbnew.NETINFO_ITEM(board, name)
                board.Add(nets[name])

    for ref, (lib, name, value, (x, y), rotation, pads) in PARTS.items():
        footprint = pcbnew.FootprintLoad(f"{LIB}/{lib}.pretty", name)
        if footprint is None:
            raise SystemExit(f"missing footprint {lib}:{name}")
        footprint.SetFPIDAsString(f"{lib}:{name}")
        footprint.SetReference(ref)
        footprint.SetValue(value)
        footprint.SetPosition(pcbnew.VECTOR2I_MM(x, y))
        footprint.SetOrientationDegrees(rotation)
        board.Add(footprint)
        for pad in footprint.Pads():
            net = pads.get(pad.GetNumber())
            if net:
                pad.SetNet(nets[net])
    board.Save(out)




def pour_ground(src: str, out: str) -> None:
    """After routing: fill GND on both copper layers, so ground is one connected plane."""
    board = pcbnew.LoadBoard(src)
    gnd = board.FindNet("GND")
    # The USB connector's shield tabs join the pour solidly; thermal spokes starve on those slots.
    for pad in board.FindFootprintByReference("J1").Pads():
        if pad.GetNumber() == "6":
            pad.SetLocalZoneConnection(pcbnew.ZONE_CONNECTION_FULL)
    for layer in (pcbnew.F_Cu, pcbnew.B_Cu):
        zone = pcbnew.ZONE(board)
        zone.SetLayer(layer)
        zone.SetNet(gnd)
        zone.SetLocalClearance(pcbnew.FromMM(0.3))
        zone.SetMinThickness(pcbnew.FromMM(0.25))
        zone.SetPadConnection(pcbnew.ZONE_CONNECTION_THERMAL)
        outline = zone.Outline()
        outline.NewOutline()
        for x, y in ((0.5, 0.5), (79.5, 0.5), (79.5, 49.5), (0.5, 49.5)):
            outline.Append(pcbnew.FromMM(x), pcbnew.FromMM(y))
        board.Add(zone)
    pcbnew.ZONE_FILLER(board).Fill(board.Zones())
    board.Save(out)


def write_project(pcb: str) -> None:
    """KiCad keeps design rules in the project file next to the board: state the 0.2 mm minimum drill
    the ESP32-WROOM-32 footprint's thermal vias need."""
    import json
    from pathlib import Path

    rules = {"board": {"design_settings": {"rules": {"min_through_hole_diameter": 0.2, "min_via_annular_width": 0.1}}},
             "meta": {"filename": Path(pcb).with_suffix(".kicad_pro").name, "version": 1}}
    Path(pcb).with_suffix(".kicad_pro").write_text(json.dumps(rules, indent=2) + "\n")


if __name__ == "__main__":
    if sys.argv[1] == "pour":  # pour IN_ROUTED OUT
        pour_ground(sys.argv[2], sys.argv[3])
        write_project(sys.argv[3])
    else:
        build(sys.argv[1])
