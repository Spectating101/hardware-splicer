"""Build revision B of the ESP32 pan/tilt servo controller board, end to end.

Revision A (examples/main_ctrl_esp32_servo.kicad_pcb, generated by HS in June 2026) fails KiCad DRC
and, checked against KiCad's own symbol library, is wired to the wrong pins:

* ESP32-WROOM-32 pin 1 is GND but carried +3V3; pin 2 (VDD) carried EN; pin 3 (EN) was open.
* The CP2102 UART sat on pins 22/23 (GPIO.4 / CTS); RXD and TXD are pins 25 and 26.
* GPIO0 was pulled high with no button or auto-reset, so the board could not enter its bootloader.
* Its footprints were not KiCad library footprints; the USB connector's own pads overlapped.

Revision B keeps the function and the pan/tilt spec (examples/hardware_splicer_closed_mechatronics_demo.json:
80 x 50 mm, 2 layers, 0.15 mm trace/space, 0.3 mm minimum drill, M2 holes at (6, 6) and (74, 44), USB
in the front-edge cutout x 36-46) and adds what the review found missing:

* KiCad library footprints, pins checked against KiCad symbols (tests/test_esp32_board_rev_b.py).
* CP2102N-A02-GQFN28 with its regulator unused: VDD and VREGIN on +3V3 with 4.7 uF + 100 nF at the
  chip, VBUS sensed through a 22.1k / 47.5k divider, RSTb pulled up with 1k (CP2102N datasheet).
* USBLC6-2SC6 ESD protection on D+, D- and VBUS; the USB entry (J1 -> U4 -> U2) is routed by hand
  (locked copper laid before autorouting), with the one D+/D- swap the part numbering forces done
  through two vias.
* 10 uF + 100 nF at the ESP32's VDD; 22 uF on the AMS1117 output, 10 uF on its input.
* BOOT and RESET buttons plus DTR/RTS auto-reset (two MMBT3904, ESP32 DevKitC style); EN RC delay.
* 4.7k I2C pull-ups on SDA and SCL. I2C is on IO32/IO33 and servo PWM on IO25/IO26 (rev A: IO18/IO19,
  IO16/IO17), on the module's side that faces the board; firmware must use these pins.
* SERVO_5V: the input beside the servo header, a 470 uF bulk capacitor at the header, and 1.0 mm
  top copper laid by hand before the autorouter; VBUS and +3V3 widened to 0.4 mm where DRC allows.
* Ground is not autorouted: both layers are poured with ground after routing (isolated islands removed),
  stitched together with vias on a 4 mm grid wherever a via sits inside both fills, and any ground pad
  the pours still cannot reach gets its own via, kept only if DRC stays clean.
* The ESP32 antenna flush with the top edge; its keepout carries no copper. The module's underside is
  solder-masked apart from its castellated pads and centre ground pad, which DRC keeps clear.

Software evidence only: nothing here has been fabricated, powered or flashed.

Pipeline (one command; KiCad's pcbnew Python for the board steps, HS's routing engine with
FreeRouting for routing):

  python3 scripts/build_esp32_servo_rev_b.py all examples/main_ctrl_esp32_servo_rev_b.kicad_pcb

Environment: KICAD_FOOTPRINT_DIR (default /usr/share/kicad/footprints); HARDWARE_SPLICER_FREEROUTING_JAR
(default ~/.local/share/freerouting/freerouting-2.1.0.jar); HS_PYTHON, the Python that runs HS's
routing engine (default .venv/bin/python, else this interpreter).
"""

