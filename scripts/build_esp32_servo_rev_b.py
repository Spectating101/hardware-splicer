# Pads joined to the ground pour without thermal spokes: USB shield tabs, servo return current.
SOLID_GND = {("J1", "6"), ("J3", "1"), ("J4", "2")}


def _pcbnew():
    import pcbnew  # KiCad's Python; imported lazily so the spec can be read without KiCad

    return pcbnew


def build(out: str) -> None:
    """Place every part with its nets, drop the ESP32 footprint's 0.2 mm thermal-via pads (the spec's
    minimum drill is 0.3 mm), pre-route SERVO_5V and fill the bottom ground plane."""
    pcbnew = _pcbnew()
    board = pcbnew.BOARD()
    board.GetDesignSettings().SetBoardThickness(pcbnew.FromMM(1.6))
    corners = [(0, 0), (BOARD_W, 0), (BOARD_W, BOARD_H), (0, BOARD_H)]
    for (x0, y0), (x1, y1) in zip(corners, corners[1:] + corners[:1]):
        edge = pcbnew.PCB_SHAPE(board)
        edge.SetShape(pcbnew.SHAPE_T_SEGMENT)
        edge.SetStart(pcbnew.VECTOR2I_MM(x0, y0))
        edge.SetEnd(pcbnew.VECTOR2I_MM(x1, y1))
        edge.SetLayer(pcbnew.Edge_Cuts)
        edge.SetWidth(pcbnew.FromMM(0.15))
        board.Add(edge)

    nets = {}
    for _, _, _, _, _, pads in PARTS.values():
        for name in pads.values():
            if name not in nets:
                nets[name] = pcbnew.NETINFO_ITEM(board, name)
                board.Add(nets[name])

    for ref, (lib, name, value, (x, y), rotation, pads) in PARTS.items():
        footprint = pcbnew.FootprintLoad(f"{LIB}/{lib}.pretty", name)
        if footprint is None:
            raise SystemExit(f"missing footprint {lib}:{name}")
        footprint.SetFPIDAsString(f"{lib}:{name}")
        footprint.SetReference(ref)
        footprint.SetValue(value)
        footprint.SetPosition(pcbnew.VECTOR2I_MM(x, y))
        footprint.SetOrientationDegrees(rotation)
        if ref == "U1":
            for pad in list(footprint.Pads()):
                if pad.GetNumber() == "39" and pad.GetDrillSize().x > 0:
                    footprint.Remove(pad)
        board.Add(footprint)
        for pad in footprint.Pads():
            net = pads.get(pad.GetNumber())
            if net:
                pad.SetNet(nets[net])
            # Small surface-mount ground pads starve thermal spokes; join them (and the listed
            # high-current or shield pads) to the pour solidly.
            smd_ground = net == "GND" and pad.GetAttribute() == pcbnew.PAD_ATTRIB_SMD
            if (ref, pad.GetNumber()) in SOLID_GND or smd_ground:
                pad.SetLocalZoneConnection(pcbnew.ZONE_CONNECTION_FULL)

    _lay_hand_routes(board, pcbnew)
    # No ground pour before routing: KiCad exports a ground zone to the router as a plane that takes
    # its whole layer, which leaves the signals one layer. Both layers are poured after routing.
    board.Save(out)


def _pad(board, ref: str, number: str):
    # Iterate rather than FindFootprintByReference: on a loaded board that returns an unwrapped SWIG object.
    footprint = next(fp for fp in board.GetFootprints() if fp.GetReference() == ref)
    return next(pad for pad in footprint.Pads() if pad.GetNumber() == number)


HAND_GROUND_PADS = {("U4", "2")}  # ground pads whose hand-routed via must stay connected during routing


def _hand_routes(board, pcbnew):
    """Routes laid by hand after autorouting, in mm: (net, layer, width, points) and (net, x, y) vias.

    USB entry: J1 -> USBLC6 (U4) -> CP2102N (U2). With every part on top, the connector and the QFN
    number D+/D- in opposite senses, so the pair must swap once: D+ drops to bottom copper through two
    vias under D-. U4's VBUS pin sits between the data lines (reached by a via from a spur off the
    connector's VBUS route to C9) and its GND pin below them (a via to the ground plane).
    Servo supply: J4 pin 1 to J3 pin 2 and C8's positive pad, 1.0 mm, on top copper below C8's pads, so
    the bottom ground plane stays unbroken."""
    mm = pcbnew.ToMM
    def at(ref, number):
        position = _pad(board, ref, number).GetPosition()
        return mm(position.x), mm(position.y)
    p3, p2, p1 = at("J1", "3"), at("J1", "2"), at("J1", "1")
    a6, a5, a4, b1, b2, b3 = at("U4", "6"), at("U4", "5"), at("U4", "4"), at("U4", "1"), at("U4", "2"), at("U4", "3")
    q4, q5 = at("U2", "4"), at("U2", "5")
    c9 = at("C9", "1")
    j4, j3, cap = at("J4", "1"), at("J3", "2"), at("C8", "1")
    v_dp_top, v_dp_bottom = (b1[0], b1[1] + 1.26), (q4[0] + 0.6, q4[1] - 1.45)
    v_bus_slot, v_bus_spur, v_gnd = (a5[0], a5[1] - 2.06), (p1[0] + 1.3, p1[1] + 1.85), (b2[0], b2[1] + 1.26)
    lane = cap[1] + 4.0
    tracks = [
        ("USB_D+", "F", 0.2, [p3, (p3[0], p3[1] + 1.45), (a6[0], p3[1] + 2.1), a6]),
        ("USB_D-", "F", 0.2, [p2, (p2[0], p2[1] + 1.85), (a4[0], p2[1] + 2.45), a4]),
        # Flow-through: each channel's two pins are joined under the package, pin to pin.
        ("USB_D+", "F", 0.2, [a6, b1]),
        ("USB_D-", "F", 0.2, [a4, b3]),
        ("USB_D+", "F", 0.2, [b1, v_dp_top]),
        ("USB_D+", "B", 0.2, [v_dp_top, v_dp_bottom]),
        ("USB_D+", "F", 0.2, [v_dp_bottom, (q4[0], v_dp_bottom[1] + 0.6), q4]),
        ("USB_D-", "F", 0.2, [b3, (b3[0], b3[1] + 1.46), (q5[0], b3[1] + 1.46 + (b3[0] - q5[0])), q5]),
        ("VBUS", "F", 0.4, [p1, (p1[0], p1[1] + 1.15), (p1[0] + 0.7, p1[1] + 1.85), (c9[0], p1[1] + 1.85), c9]),
        ("VBUS", "B", 0.3, [v_bus_spur, v_bus_slot]),
        ("VBUS", "F", 0.3, [v_bus_slot, a5]),
        ("GND", "F", 0.3, [b2, v_gnd]),
        ("SERVO_5V", "F", SERVO_WIDTH_MM, [j4, (j4[0], lane), (j3[0], lane), j3]),
        ("SERVO_5V", "F", SERVO_WIDTH_MM, [cap, (cap[0], lane)]),
    ]
    vias = [("USB_D+",) + v_dp_top, ("USB_D+",) + v_dp_bottom, ("VBUS",) + v_bus_slot, ("VBUS",) + v_bus_spur, ("GND",) + v_gnd]
    return tracks, vias


def _lay_hand_routes(board, pcbnew) -> None:
    """Lay the hand routes before autorouting, locked: KiCad exports locked copper to the router as
    protected wiring, which it routes around and leaves unchanged (HS's router guard refuses any change
    to existing copper). Locked here means "hand-routed"."""
    tracks, vias = _hand_routes(board, pcbnew)
    nets = {net.GetNetname(): net for net in board.GetNetInfo().NetsByName().values()}
    for net, side, width, points in tracks:
        layer = pcbnew.F_Cu if side == "F" else pcbnew.B_Cu
        for (xa, ya), (xb, yb) in zip(points, points[1:]):
            _segment(board, pcbnew, nets[net], pcbnew.FromMM(xa), pcbnew.FromMM(ya),
                     pcbnew.FromMM(xb), pcbnew.FromMM(yb), layer, width, locked=True)
    for net, x, y in vias:
        via = pcbnew.PCB_VIA(board)
        via.SetPosition(pcbnew.VECTOR2I_MM(x, y))
        via.SetDrill(pcbnew.FromMM(0.3))
        via.SetWidth(pcbnew.F_Cu, pcbnew.FromMM(0.6))
        via.SetNet(nets[net])
        via.SetLocked(True)
        board.Add(via)


def _add_ground_zone(board, pcbnew, gnd, layer) -> None:
    zone = pcbnew.ZONE(board)
    zone.SetLayer(layer)
    zone.SetNet(gnd)
    zone.SetLocalClearance(pcbnew.FromMM(0.3))
    zone.SetMinThickness(pcbnew.FromMM(0.25))
    zone.SetPadConnection(pcbnew.ZONE_CONNECTION_THERMAL)
    zone.SetThermalReliefSpokeWidth(pcbnew.FromMM(0.4))
    zone.SetIslandRemovalMode(pcbnew.ISLAND_REMOVAL_MODE_ALWAYS)  # no floating copper
    outline = zone.Outline()
    outline.NewOutline()
    for x, y in ((0.5, 0.5), (BOARD_W - 0.5, 0.5), (BOARD_W - 0.5, BOARD_H - 0.5), (0.5, BOARD_H - 0.5)):
        outline.Append(pcbnew.FromMM(x), pcbnew.FromMM(y))
    board.Add(zone)


def _segment(board, pcbnew, net, xa, ya, xb, yb, layer, width_mm: float = SERVO_WIDTH_MM, locked: bool = False) -> None:
    if (xa, ya) == (xb, yb):
        return
    track = pcbnew.PCB_TRACK(board)
    track.SetStart(pcbnew.VECTOR2I(xa, ya))
    track.SetEnd(pcbnew.VECTOR2I(xb, yb))
    track.SetWidth(pcbnew.FromMM(width_mm))
    track.SetLayer(layer)
    track.SetNet(net)
    track.SetLocked(locked)
    board.Add(track)


def widen(pcb: str, nets: tuple[str, ...] = ("VBUS", "+3V3"), width_mm: float = POWER_WIDTH_MM) -> None:
    """Widen the routed power nets, then back off every segment KiCad DRC flags (one process per round)."""
    record = pcb + ".widths.json"
    _step("widenapply", pcb, ",".join(nets), str(width_mm), record)
    for _ in range(6):
        original = json.loads(Path(record).read_text())
        flagged = sorted({item["uuid"] for row in drc(pcb)["violations"] if row["severity"] == "error"
                          for item in row["items"] if item["uuid"] in original})
        if not flagged:
            break
        _step("widenrevert", pcb, record, ",".join(flagged))
    Path(record).unlink(missing_ok=True)


def settle(pcb: str) -> None:
    """Last word on track widths: a widened power track (unlocked, so not hand-routed) still in a DRC
    error goes back to the router's 0.2 mm; any other unlocked track in one (the router's geometry
    occasionally rounds a hair under clearance) is trimmed by 0.02 mm, never below the spec's 0.15 mm.
    The zones refill after each round (one process per round)."""
    for _ in range(4):
        flagged = sorted({item["uuid"] for row in drc(pcb)["violations"] if row["severity"] == "error"
                          for item in row["items"] if item["description"].startswith("Track")})
        if not flagged:
            return
        _step("narrow", pcb, ",".join(flagged))


def narrow(pcb: str, uuids: str) -> None:
    pcbnew = _pcbnew()
    board = pcbnew.LoadBoard(pcb)
    for track in board.GetTracks():
        if track.m_Uuid.AsString() not in uuids.split(",") or track.IsLocked() or track.GetClass() != "PCB_TRACK":
            continue
        if track.GetNetname() in ("VBUS", "+3V3") and track.GetWidth() > pcbnew.FromMM(0.2):
            track.SetWidth(pcbnew.FromMM(0.2))
        elif track.GetWidth() - pcbnew.FromMM(0.02) >= pcbnew.FromMM(0.15):
            track.SetWidth(track.GetWidth() - pcbnew.FromMM(0.02))
    pcbnew.ZONE_FILLER(board).Fill(board.Zones())
    board.Save(pcb)


def widen_apply(pcb: str, nets: str, width_mm: str, record: str) -> None:
    pcbnew = _pcbnew()
    board = pcbnew.LoadBoard(pcb)
    original = {}
    for track in board.GetTracks():
        if track.GetClass() == "PCB_TRACK" and track.GetNetname() in nets.split(",") and track.GetWidth() < pcbnew.FromMM(float(width_mm)):
            original[track.m_Uuid.AsString()] = track.GetWidth()
            track.SetWidth(pcbnew.FromMM(float(width_mm)))
    board.Save(pcb)
    Path(record).write_text(json.dumps(original))


def widen_revert(pcb: str, record: str, flagged: str) -> None:
    pcbnew = _pcbnew()
    original = json.loads(Path(record).read_text())
    board = pcbnew.LoadBoard(pcb)
    for track in board.GetTracks():
        uuid = track.m_Uuid.AsString()
        if uuid in flagged.split(","):
            track.SetWidth(original.pop(uuid))
    board.Save(pcb)
    Path(record).write_text(json.dumps(original))


def pour_ground(pcb: str) -> None:
    """Pour ground on both layers after routing and fill them."""
    pcbnew = _pcbnew()
    board = pcbnew.LoadBoard(pcb)
    gnd = board.FindNet("GND")
    layers = {zone.GetLayer() for zone in board.Zones() if not zone.GetIsRuleArea() and zone.GetNetname() == "GND"}
    for layer in (pcbnew.F_Cu, pcbnew.B_Cu):
        if layer not in layers:
            _add_ground_zone(board, pcbnew, gnd, layer)
    pcbnew.ZONE_FILLER(board).Fill(board.Zones())
    board.Save(pcb)


def remove_tracks(pcb: str, uuids_file: str) -> None:
    pcbnew = _pcbnew()
    uuids = set(json.loads(Path(uuids_file).read_text()))
    board = pcbnew.LoadBoard(pcb)
    for track in [track for track in board.GetTracks() if track.m_Uuid.AsString() in uuids]:
        board.Delete(track)
    pcbnew.ZONE_FILLER(board).Fill(board.Zones())
    board.Save(pcb)


def remove_dangling(pcb: str) -> int:
    """Delete track stubs KiCad DRC reports as dangling (left by the router); repeat until none."""
    removed = 0
    for _ in range(8):
        uuids = sorted({item["uuid"] for row in drc(pcb)["violations"] if row["type"] == "track_dangling" for item in row["items"]})
        if not uuids:
            break
        with tempfile.NamedTemporaryFile("w", suffix=".json", delete=False) as handle:
            json.dump(uuids, handle)
        _step("removetracks", pcb, handle.name)
        Path(handle.name).unlink(missing_ok=True)
        removed += len(uuids)
    return removed


def drc(pcb: str) -> dict:
    with tempfile.TemporaryDirectory() as work:
        report = Path(work) / "drc.json"
        subprocess.run(["kicad-cli", "pcb", "drc", "--format", "json", "--severity-all", "-o", str(report), pcb],
                       capture_output=True, check=False)
        return json.loads(report.read_text())


def route(src: str, out: str) -> dict:
    """Route with HS's routing engine (FreeRouting), keeping the pre-routed SERVO_5V copper."""
    hs_python = os.environ.get("HS_PYTHON") or (str(ROOT / ".venv/bin/python") if (ROOT / ".venv/bin/python").exists() else sys.executable)
    env = dict(os.environ, PYTHONPATH=str(ROOT / "src"),
               HARDWARE_SPLICER_KICAD_PYTHON=os.environ.get("HARDWARE_SPLICER_KICAD_PYTHON", shutil.which("python3") or "python3"),
               HARDWARE_SPLICER_FREEROUTING_JAR=os.environ.get(
                   "HARDWARE_SPLICER_FREEROUTING_JAR", str(Path.home() / ".local/share/freerouting/freerouting-2.1.0.jar")),
               # FreeRouting 2.1.0 finishes this board in a few passes on its own, but with -mp it runs on
               # for hundreds of passes and ends worse; HS's documented flag override points the pass
               # count at -dct (a dialog timeout, inert when headless) instead.
               HARDWARE_SPLICER_FREEROUTING_MP_FLAG=os.environ.get("HARDWARE_SPLICER_FREEROUTING_MP_FLAG", "-dct"))
    code = ("import json,sys; from pathlib import Path; from hardware_splicer.routing_engine import route_pcb;"
            "r=route_pcb(Path(sys.argv[1]).read_text(), timeout_s=900, max_passes=40, keep_existing_tracks=True);"
            "Path(sys.argv[2]).write_text(r.text); print(json.dumps({'engine': r.engine, 'stats': r.stats}))")
    done = subprocess.run([hs_python, "-c", code, src, out], env=env, capture_output=True, text=True, check=False)
    if done.returncode != 0:
        raise SystemExit(f"routing failed: {done.stderr[-2000:]}")
    return json.loads(done.stdout.strip().splitlines()[-1])


def set_ground_pads(pcb: str, connected: bool) -> None:
    """Ground comes from the pours, not the router: GND pads go to the router unassigned (still obstacles)
    and get their net back afterwards."""
    pcbnew = _pcbnew()
    board = pcbnew.LoadBoard(pcb)
    gnd, none = board.FindNet("GND"), board.FindNet("")
    for footprint in board.GetFootprints():
        nets = PARTS[footprint.GetReference()][5]
        for pad in footprint.Pads():
            if nets.get(pad.GetNumber()) == "GND" and (footprint.GetReference(), pad.GetNumber()) not in HAND_GROUND_PADS:
                pad.SetNet(gnd if connected else none)
    board.Save(pcb)


def stitch_planes(pcb: str, pitch_mm: float = 4.0) -> int:
    """Ground stitching: a via wherever one sits wholly inside the ground fill on both layers, on a
    grid, so the top pour's pieces and the bottom plane are one ground. Inside both fills means the
    fills' own clearance keeps the via away from every other net."""
    import math

    pcbnew = _pcbnew()
    board = pcbnew.LoadBoard(pcb)
    gnd = board.FindNet("GND")
    fills = {}
    for zone in board.Zones():
        if not zone.GetIsRuleArea() and zone.GetNetname() == "GND":
            fills[zone.GetLayer()] = zone.GetFilledPolysList(zone.GetLayer())
    if set(fills) != {pcbnew.F_Cu, pcbnew.B_Cu}:
        return 0
    taken = [(pcbnew.ToMM(item.GetPosition().x), pcbnew.ToMM(item.GetPosition().y))
             for item in board.GetTracks() if item.GetClass() == "PCB_VIA"]
    # Keep clear of through-hole pads: a fill joined solidly to one would otherwise accept a via inside it.
    pads = [(pcbnew.ToMM(pad.GetPosition().x), pcbnew.ToMM(pad.GetPosition().y),
             pcbnew.ToMM(max(pad.GetSize().x, pad.GetSize().y)) / 2 + 0.7)
            for fp in board.GetFootprints() for pad in fp.Pads() if pad.GetAttribute() == pcbnew.PAD_ATTRIB_PTH]
    ring = [(0.55 * math.cos(2 * math.pi * k / 12), 0.55 * math.sin(2 * math.pi * k / 12)) for k in range(12)] + [(0, 0)]
    added = 0
    y = pitch_mm / 2
    while y < BOARD_H:
        x = pitch_mm / 2
        while x < BOARD_W:
            inside = all(fill.Contains(pcbnew.VECTOR2I_MM(x + dx, y + dy))
                         for fill in fills.values() for dx, dy in ring)
            clear = all(math.hypot(x - px, y - py) > reach for px, py, reach in pads)
            if inside and clear and all(math.hypot(x - tx, y - ty) > 1.5 for tx, ty in taken):
                via = pcbnew.PCB_VIA(board)
                via.SetPosition(pcbnew.VECTOR2I_MM(x, y))
                via.SetDrill(pcbnew.FromMM(0.3))
                via.SetWidth(pcbnew.F_Cu, pcbnew.FromMM(0.6))
                via.SetNet(gnd)
                board.Add(via)
                taken.append((x, y))
                added += 1
            x += pitch_mm
        y += pitch_mm

    def add(x, y):
        via = pcbnew.PCB_VIA(board)
        via.SetPosition(pcbnew.VECTOR2I_MM(x, y))
        via.SetDrill(pcbnew.FromMM(0.3))
        via.SetWidth(pcbnew.F_Cu, pcbnew.FromMM(0.6))
        via.SetNet(gnd)
        board.Add(via)
        taken.append((x, y))

    # Any top-layer ground fragment the grid missed (for example under a QFN's exposed pad) gets one
    # via, found by a fine search inside it.
    top = fills[pcbnew.F_Cu]
    for index in range(top.OutlineCount()):
        outline = top.Outline(index)
        box = outline.BBox()
        if any(outline.PointInside(pcbnew.VECTOR2I_MM(tx, ty)) for tx, ty in taken):
            continue
        x0, y0 = pcbnew.ToMM(box.GetLeft()), pcbnew.ToMM(box.GetTop())
        x1, y1 = pcbnew.ToMM(box.GetRight()), pcbnew.ToMM(box.GetBottom())
        found = None
        steps_x, steps_y = int((x1 - x0) / 0.2), int((y1 - y0) / 0.2)
        for j in range(steps_y + 1):
            for i in range(steps_x + 1):
                x, y = x0 + i * 0.2, y0 + j * 0.2
                if all(outline.PointInside(pcbnew.VECTOR2I_MM(x + dx, y + dy)) and
                       fills[pcbnew.B_Cu].Contains(pcbnew.VECTOR2I_MM(x + dx, y + dy)) for dx, dy in ring):
                    found = (x, y)
                    break
            if found:
                break
        if found and all(math.hypot(found[0] - tx, found[1] - ty) > 0.9 for tx, ty in taken) and \
                all(math.hypot(found[0] - px, found[1] - py) > reach for px, py, reach in pads):
            add(*found)
            added += 1
    pcbnew.ZONE_FILLER(board).Fill(board.Zones())
    board.Save(pcb)
    print(added)
    return added


def drop_vias_in_pads(pcb: str) -> None:
    """Remove any unlocked ground via whose drill lands inside a plated through-hole pad (the pad already
    joins the layers, and co-located drills are a fabrication defect). Vias in a surface-mount exposed pad
    are thermal vias and stay."""
    pcbnew = _pcbnew()
    board = pcbnew.LoadBoard(pcb)
    pads = [pad for fp in board.GetFootprints() for pad in fp.Pads() if pad.GetAttribute() == pcbnew.PAD_ATTRIB_PTH]
    doomed = [via for via in board.GetTracks() if via.GetClass() == "PCB_VIA" and via.GetNetname() == "GND"
              and not via.IsLocked() and any(pad.HitTest(via.GetPosition()) for pad in pads)]
    for via in doomed:
        board.Delete(via)
    pcbnew.ZONE_FILLER(board).Fill(board.Zones())
    board.Save(pcb)
    print(len(doomed))


def stranded_pads(pcb: str) -> None:
    """Print, as JSON, the ground pads that sit in a top-layer ground fragment with no via in it."""
    pcbnew = _pcbnew()
    board = pcbnew.LoadBoard(pcb)
    zone = next(zone for zone in board.Zones() if not zone.GetIsRuleArea() and zone.GetNetname() == "GND"
                and zone.GetLayer() == pcbnew.F_Cu)
    fill = zone.GetFilledPolysList(pcbnew.F_Cu)
    vias = [item.GetPosition() for item in board.GetTracks() if item.GetClass() == "PCB_VIA" and item.GetNetname() == "GND"]
    through = [pad.GetPosition() for fp in board.GetFootprints() for pad in fp.Pads()
               if pad.GetNetname() == "GND" and pad.GetAttribute() == pcbnew.PAD_ATTRIB_PTH]
    stranded = []
    for index in range(fill.OutlineCount()):
        outline = fill.Outline(index)
        if any(outline.PointInside(point) for point in vias + through):
            continue
        for fp in board.GetFootprints():
            for pad in fp.Pads():
                if pad.GetNetname() == "GND" and outline.PointInside(pad.GetPosition()):
                    stranded.append((pcbnew.ToMM(pad.GetPosition().x), pcbnew.ToMM(pad.GetPosition().y)))
    print(json.dumps(stranded))


