"""Generate a connected, non-fabrication CM5 bring-up bench schematic in KiCad 9.

A4/IO not copied blindly from vendor; selected CM5 contacts come from the
manufacturer-verified V2.21 manifest. External 4V/3A current-limited supply
is an *independent required input*, not generated by this circuit.
USB HOST0 breakout is DATA/GND ONLY; no switched 5V VBUS; no real USB port.
UART2 signals are exposed for measurement only; logic voltage unqualified.
No board/gerbers and NO permission to power or fabricate hardware.
"""
from __future__ import annotations

import argparse
from collections import defaultdict
import json
from pathlib import Path
import re
from uuid import uuid5, NAMESPACE_URL

SCHEMA = "hs.cm5_connected_bench_schematic.v1"
PROJECT = "CM5_BENCH_HARNESS_NOT_FOR_FAB"
ROOTNS = "hs.cm5.bench.20261107"


def uid(name: str) -> str:
    return str(uuid5(NAMESPACE_URL,ROOTNS+":"+name))


def kquote(value: str) -> str:
    return json.dumps(str(value),ensure_ascii=True)


def sexpr_form(text: str, start: int) -> str:
    assert text[start]=="(",start
    depth=0
    in_string=False
    escaped=False
    for index in range(start,len(text)):
        c=text[index]
        if in_string:
            if escaped: escaped=False
            elif c=="\\":escaped=True
            elif c=='"':in_string=False
        elif c=='"': in_string=True
        elif c=="(":depth+=1
        elif c==")":
            depth-=1
            if not depth:return text[start:index+1]
    raise ValueError("unbalanced KiCad S-expression")


def extract_symbol(lib: str, name: str) -> str:
    token='(symbol "'+name+'"'
    pos=lib.find(token)
    if pos<0:raise ValueError("symbol missing: "+name)
    return sexpr_form(lib,pos)


def inner_library(orig: str, old: str, new: str) -> str:
    if not orig.startswith('(symbol "'+old+'"'):
        raise ValueError("unexpected library symbol")
    return orig.replace('(symbol "'+old+'"','(symbol "'+new+'"',1)


def pin_coordinates(whole: str, prefix: str, valid_units: set[int]) -> dict[int,dict[int,tuple[str,float,float,int,str]]]:
    result=defaultdict(dict)
    for unit in valid_units:
        # Unit 1_0 has only text, 1_1 is actual pins
        text=extract_symbol(whole,f"{prefix}_{unit}_1")
        pattern=re.compile(
            r'\(pin\s+([a-z_]+)\s+\w+\s+\(at\s+(-?[\d.]+)\s+(-?[\d.]+)\s+(\d+)\)'
            r'.*?\(name\s+"([^"]+)".*?\(number\s+"(\d+)"',re.S)
        pins=pattern.findall(text)
        if not pins:raise ValueError(f"unit {unit} has no symbol pins")
        for kind,x,y,angle,name,n in pins:
            n=int(n)
            if n in result[unit]:raise ValueError(f"duplicate pin {n}")
            result[unit][n]=(kind,float(x),float(y),int(angle),name)
    return result


def sym_instance(lib: str, reference: str, value: str, x: float, y: float, unit: int, key: str, footprint: str="") -> str:
    ref=uid("ref-"+key)
    fields=(f'(property "Reference" {kquote(reference)} (at {x:.4f} {y+4:.4f} 0) '
            f'(effects (font (size 1.27 1.27))))\n'
            f'(property "Value" {kquote(value)} (at {x:.4f} {y+7:.4f} 0) '
            f'(effects (font (size 1.27 1.27))))\n'
            f'(property "Footprint" {kquote(footprint)} (at {x} {y} 0)'
            ' (effects (font (size 1.27 1.27)) (hide yes)))\n')
    return (f'(symbol (lib_id {kquote(lib)}) (at {x:.4f} {y:.4f} 0)'
            f' (unit {unit}) (in_bom yes) (on_board yes) (dnp no)'
            f' (uuid {kquote(ref)})\n{fields}'
            f'(instances (project {kquote(PROJECT)} (path "/{uid("root")}"'
            f' (reference {kquote(reference)}) (unit {unit})))) )')


def wire_label(name: str, at_x: float,at_y:float, angle:int, key:str) -> tuple[str,str]:
    # Wire away from symbol body. For angle=0, pins run rightwards into body:
    # external far end is on the left. At 180, external far end is right.
    if angle==0: x2=at_x-5.08;y2=at_y
    elif angle==180:x2=at_x+5.08;y2=at_y
    elif angle==90:x2=at_x;y2=at_y-5.08
    elif angle==270:x2=at_x;y2=at_y+5.08
    else:raise ValueError(f"unsupported orientation {angle}")
    line=(f'(wire (pts (xy {at_x:.4f} {at_y:.4f}) (xy {x2:.4f} {y2:.4f}))'
          f' (stroke (width 0) (type default)) (uuid {kquote(uid("wire-"+key))}))')
    label=(f'(label {kquote(name)} (at {x2:.4f} {y2:.4f} 0)'
           f' (effects (font (size 1.0 1.0)) (justify left bottom))'
           f' (uuid {kquote(uid("label-"+key))}))')
    return line,label


def build(manifest: dict,radxa_sym: str,connectors: str,device: str, *, out: Path) -> dict:
    official={int(k):v for k,v in manifest.get("pin_names",{}).items()}
    if (manifest.get("manufacturer_revision")!="V2.21" or
            set(official)!=set(range(1,301))):
        raise ValueError("official pin manifest missing/changed")
    original=extract_symbol(radxa_sym,"Radxa_CM5")
    pins=pin_coordinates(original,"Radxa_CM5",{1,2,3})
    allpins={}
    for unit,group in pins.items():
        for number,spec in group.items():
            if number in allpins:raise ValueError("two units share the same pin")
            if spec[4]!=official[number]:
                raise ValueError(f"unit pin {number} not manufacturer named")
            allpins[number]=(unit,*spec)
    if set(allpins)!=set(range(1,301)):
        raise ValueError("symbol does not cover all 300 pins")
    # Known and approved *logical* bench harness endpoints; unverified
    # GPIO and proprietary rail outputs are NOT connected here.
    selected={number:("VCC_SYSIN" if label=="VCC_SYSIN" else
                      "GND" if label=="GND" else
                      label)
              for number,label in official.items()
              if label in {"VCC_SYSIN","GND","USB20_HOST0_DP","USB20_HOST0_DM",
                           "UART2_RX_M0","UART2_TX_M0"}}
    if sum(v=="VCC_SYSIN" for v in selected.values())!=6:
        raise ValueError("expected exactly 6 CM5 VCC_SYSIN input pins")
    if sum(v=="GND" for v in selected.values())<60:
        raise ValueError("not all module GND contacts mapped")
    # Copy symbol definition, no physical connections on unsourced pins.
    all_libraries=[
        inner_library(original,"Radxa_CM5","HS_CM5_OFFICIAL:Radxa_CM5"),
        inner_library(extract_symbol(connectors,"Conn_01x02"),"Conn_01x02","Connector_Generic:Conn_01x02"),
        inner_library(extract_symbol(connectors,"Conn_01x03"),"Conn_01x03","Connector_Generic:Conn_01x03"),
        inner_library(extract_symbol(device,"C"),"C","Device:C"),
    ]
    placements={1:(101.6,118.11),2:(241.3,118.11),3:(387.35,118.11)}
    draw=[]
    for unit,(x,y) in placements.items():
        draw.append(sym_instance("HS_CM5_OFFICIAL:Radxa_CM5","U1","Radxa_CM5_V2.21",x,y,unit,f"cm5-unit{unit}",
                                 "HS_CM5_OFFICIAL:Radxa_CM5"))
    connected={}
    for number,net in sorted(selected.items()):
        unit,kind,px,py,angle,_=allpins[number]
        ox,oy=placements[unit]
        anchor_x=ox+px
        anchor_y=oy-py
        wire,label=wire_label(net,anchor_x,anchor_y,angle,"U1-"+str(number))
        draw.extend((wire,label))
        connected[number]=net
    # Official NC only: indicate no-connect; do not misclassify undefined
    # signals on other pins. Their open states are still ERC findings.
    for number,name in sorted(official.items()):
        if name!="NC":continue
        unit,kind,px,py,angle,_=allpins[number]
        ox,oy=placements[unit]
        draw.append(f'(no_connect (at {ox+px:.4f} {oy-py:.4f}) (uuid {kquote(uid("nc-"+str(number)))}) )')
    # KiCad generic connectors' pin positions are -5.08 X left and
    # Y 0, -2.54 etc, verified from standard KiCad library.
    connectors_desc=[
        ("J1","REGULATED_4V_3A_INPUT_ONLY",2,(86.36,289.56),["VCC_SYSIN","GND"]),
        ("J2","USB2_HOST0_SIGNAL_ONLY_NO_VBUS",3,(241.3,289.56),
          ["USB20_HOST0_DP","USB20_HOST0_DM","GND"]),
        ("J3","UART2_LOGIC_LEVEL_NOT_VERIFIED",3,(387.35,289.56),
          ["UART2_TX_M0","UART2_RX_M0","GND"]),
    ]
    for ref,value,num,(x,y),names in connectors_desc:
        if num not in (2,3):raise ValueError("unsupported generic connector")
        draw.append(sym_instance(f"Connector_Generic:Conn_01x0{num}",ref,value,x,y,1,ref))
        for index,name in enumerate(names):
            anchor=(x-5.08,y+2.54*(index if num==2 else index-1)) 
            wire,label=wire_label(name,*anchor,0,ref+"-"+str(index+1))
            draw.extend((wire,label))
    # Capacitors: KiCad Device:C pins are along Y at +-3.81mm
    # (checked via symbol definition); avoid assigning a fake part number
    # or falsely claiming their position is fully engineered.
    for ref,value,x in [("C1","22uF_10V_UNQUALIFIED",294.64),
                        ("C2","100nF_10V_UNQUALIFIED",325.12)]:
        draw.append(sym_instance("Device:C",ref,value,x,314.96,1,ref))
        for name,angle,dy in [("VCC_SYSIN",90,-3.81),("GND",270,3.81)]:
            draw.extend(wire_label(name,x,314.96+dy,angle,ref+"-"+name))
    # Physical power and USB ESD not designed here; explanatory warnings
    # included as graphic text without implying tested circuit readiness.
    text_notes=[
        (70,260,"BENCH INPUT: external current-limited and measured 4V / 3A only"),
        (226,260,"USB HOST0: D+/D-/GND only; NO 5V VBUS switch, not usable port"),
        (368,260,"UART2: logic voltage UNVERIFIED, probe/level-shift first"),
        (72,335,"UNCONNECTED OPTIONAL SIGNALS ARE NOT ASSUMED SAFE TO FABRICATE"),
        (72,345,"V2.21 PIN 290=NC; V2.200 carrier routed RTC_32K_SOC -> BLOCKER"),
    ]
    for n,(x,y,text) in enumerate(text_notes):
        draw.append(
            f'(text {kquote(text)} (at {x:.4f} {y:.4f} 0)'
            f' (effects (font (size 1.3 1.3)) (justify left bottom))'
            f' (uuid {kquote(uid("text-"+str(n)))}) )'
        )
    sheet=(f'(kicad_sch (version 20250114) (generator "eeschema")'
           f' (uuid {kquote(uid("root"))}) (paper "A2") '
           f' (title_block (title "HS CM5 power USB2 UART bringup HARNESS - NOT FOR FAB")'
           f' (rev "RESEARCH ONLY"))'
           f' (lib_symbols\n'+"\n".join(all_libraries)+')\n'
           + "\n".join(draw)+
           ' (embedded_fonts no) )\n')
    out.parent.mkdir(parents=True,exist_ok=True)
    out.write_text(sheet,encoding="utf-8")
    return {"schema":SCHEMA,"out":str(out),"manufacturer_contacts":300,
            "cm5_vcc_sysin_pins_connected":sum(v=="VCC_SYSIN" for v in connected.values()),
            "cm5_ground_contacts_labeled":sum(v=="GND" for v in connected.values()),
            "official_nc_contacts_marked":sum(v=="NC" for v in official.values()),
            "usb2_host0_data_contacts_labeled":sum(v.startswith("USB20_HOST0") for v in connected.values()),
            "uart2_contact_count":sum(v.startswith("UART2") for v in connected.values()),
            "external_regulated_power_only":True,"usb_vbus_switch_present":False,
            "all_cm5_signal_pins_electrically_verified":False,"fabrication_authorized":False}


def main():
    a=argparse.ArgumentParser()
    a.add_argument("--vendor",type=Path,required=True)
    a.add_argument("--symbol",type=Path,required=True)
    a.add_argument("--connector-library",type=Path,required=True)
    a.add_argument("--device-library",type=Path,required=True)
    a.add_argument("--output",type=Path,required=True)
    opts=a.parse_args()
    report=build(json.loads(opts.vendor.read_text()),
                 opts.symbol.read_text(),opts.connector_library.read_text(),
                 opts.device_library.read_text(),out=opts.output)
    print(json.dumps(report,indent=2))


if __name__=="__main__":
    main()
