"""Frozen source-backed versus plain Gemini pilot, original Game Boy.

No access to the later repair method or reported component outcome.
Primary physical circuitry is Gekkio's pinned reverse engineered KiCad
mainboard revision DMG-CPU-06, not generated by Gemini. Only its netlist,
no photographs, boardviews or actual technician measurements.
"""
from __future__ import annotations

import argparse
import json
import os
from pathlib import Path

from hardware_splicer.restoration_schematic_grounding import (
    build_case_context, build_reference_tool_result,
)
from hardware_splicer.restoration_reasoning_agent import agy_chat, diagnose, sha

HERE=Path(__file__).resolve().parent
MODEL="gemini-3.8-flash-low"
BOARD="DMG-CPU-06"
ORDER=("plain","hs_real_kicad")

def protocol()->dict:
    return {
        "schema":"hs.restoration.real_schematic_pilot_ab.v1",
        "source_case_url":"https://revamp.top/gameboy/gameboy-dmg-no-power-battery-contact/",
        "source_case_intake_only":"works with external adapter; does not start with AA batteries; board revision DMG-CPU-06 reported",
        "source_case_board_physically_verified":False,
        "schematic_repo":"https://github.com/Gekkio/gb-schematics",
        "schematic_commit":"032eb9c2578125b157ab88048113b2d52663b819",
        "model":MODEL,"arm_order":list(ORDER),
        "control":"native HS repair intake and existing Gemini reasoning prompt",
        "treatment":"same native intake with validated real KiCad net connections and source graph",
        "same_input_symptoms_and_model":True,
        "one_model_call_per_arm":True,
        "creator_repair_outcomes_never_loaded":True,
        "source_variant_guard":"reference DMG-CPU-06; converter board subtype unverified and exact converter mapping withheld",
        "infer_component_current_or_actual_working_path":False,
        "physical_repair_or_test_by_HS":False,
        "accuracy_not_inferable_without_outcome_review":True,
    }

def run(*, source_checkout:Path|None,model_timeout:int,out:Path)->dict:
    # Check actual source KiCad file hashes against pinned commit when a
    # source checkout is provided; the derived netlist JSON is always checked.
    ref=build_reference_tool_result(
        reported_board_revision=BOARD,source_checkout=source_checkout)
    control=build_case_context(reported_board_revision=BOARD)
    candidate=build_case_context(reported_board_revision=BOARD,tool_reference=ref)
    if control["evidence_sha256"]!=candidate["evidence_sha256"]:
        raise ValueError("real schematic arm changed the raw repair symptoms")
    data={
        "protocol":protocol(),"protocol_sha256":sha(protocol()),
        "native_repair_intake_evidence_sha256":control["evidence_sha256"],
        "real_reference_netlist_sha256":ref["reference_snapshot_sha256"],
        "real_source_graph_sha256":ref["native_HS_engineering_source_graph_sha256"],
        "tool_result":ref,"arms":{},"complete":False,
    }
    out.parent.mkdir(parents=True,exist_ok=True)
    for arm in ORDER:
        ctx=control if arm=="plain" else candidate
        row=diagnose(ctx,inference=agy_chat,model=MODEL,timeout_s=model_timeout)
        data["arms"][arm]=row
        temp=out.with_name(out.name+".tmp")
        temp.write_text(json.dumps(data,indent=2,ensure_ascii=False)+"\n")
        os.replace(temp,out)
        print(json.dumps({
            "arm":arm,"status":row["status"],"seconds":row["elapsed_seconds"],
            "top_hypothesis":(
                row["plan"]["hypotheses"][0]["mechanism"]
                if row["plan"] and row["plan"]["hypotheses"] else None
            ),"next_check":row["plan"]["next_safe_check"] if row["plan"] else None
        }),flush=True)
    data["complete"]=True
    temp=out.with_name(out.name+".tmp")
    temp.write_text(json.dumps(data,indent=2,ensure_ascii=False)+"\n")
    os.replace(temp,out)
    return data

def main():
    p=argparse.ArgumentParser()
    p.add_argument("--source-checkout",type=Path)
    p.add_argument("--out",type=Path,required=True)
    p.add_argument("--timeout",type=int,default=70)
    a=p.parse_args()
    if a.out.exists():
        raise SystemExit("Existing sealed run cannot be silently overwritten")
    result=run(source_checkout=a.source_checkout,model_timeout=a.timeout,out=a.out)
    print(json.dumps({
        "complete":result["complete"],
        "same_symptom_sha":result["native_repair_intake_evidence_sha256"],
        "source_graph_sha":result["real_source_graph_sha256"],
        "statuses":{key:value["status"] for key,value in result["arms"].items()},
    },indent=2))

if __name__=="__main__":
    main()
