"""A tiny, hinge-pin clamshell for an ESP32 LCD + I2C keyboard.

CAD-only module for the existing Mecha-Splicer bundle engine.
Two separate printable tray halves and a posed assembly preview.
No unmeasured vendor mounting-hole positions or USB cutouts invented.
"""
from __future__ import annotations

from ..spec import ClamshellTerminalSpec


def generate_clamshell_terminal_scad(p: ClamshellTerminalSpec) -> dict[str, str]:
    w, d = p.case_w_mm, p.case_d_mm
    wall, floor = p.wall_mm, p.floor_mm
    hb, hl, gap = p.base_h_mm, p.lid_h_mm, p.closed_gap_mm
    hinge_y = d + p.hinge_y_offset_mm
    hinge_z = hb + gap/2
    hinge_r = p.hinge_outer_d_mm/2
    hinge_bore = p.hinge_pin_d_mm + 2*p.pin_radial_clearance_mm

    # Use two outer knuckles on the base and one inner knuckle on lid,
    # each physically merged with an edge wall. At angle 0 the lid is
    # above the base (open faces meet); at -135 degrees it opens upward.
    margin = p.knuckle_end_margin_mm
    left_span = p.knuckle_outer_length_mm
    right_x = w - margin - left_span
    inner_x = margin + left_span + p.knuckle_axial_gap_mm
    inner_len = w - 2*(margin+left_span+p.knuckle_axial_gap_mm)
    cable_x = margin+left_span+(p.knuckle_axial_gap_mm-p.cable_slot_w_mm)/2

    def header(part: str) -> list[str]:
        return [
            "// Generated by Mecha-Splicer: clamshell_terminal v1",
            "// Dimension-based CAD ONLY: unknown PCB screw positions, USB access and real fit.",
            f"// {part}, all dimensions in mm",
            "$fn=56;",
            f"W={w}; D={d}; wall={wall}; floor={floor};",
            f"HBASE={hb}; HLID={hl}; gap={gap};",
            f"hy={hinge_y}; hz={hinge_z};",
            f"kr={hinge_r}; bore={hinge_bore};",
            "",
        ]
    base=header("base / keyboard tray")
    base += [
        "module base_shell() {",
        "  difference() {",
        "    union() {",
        "      difference() {",
        "        cube([W,D,HBASE]);",
        "        translate([wall,wall,floor]) cube([W-2*wall,D-2*wall,HBASE+1]);",
        "      }",
        # outer knuckles use X-axis bore, cross into shell for structural connection
        f"      for (x=[{margin},{right_x}]) "
        f"translate([x,hy,hz]) rotate([0,90,0]) "
        f"cylinder(h={left_span},r=kr);",
        "    }",
        "    // Strain-relief entry only: actual cable bend life remains untested",
        f"    translate([{cable_x},{d-wall-0.1},{hb-p.cable_slot_h_mm}]) "
        f"cube([{p.cable_slot_w_mm},{wall+0.2},{p.cable_slot_h_mm+0.1}]);",
        "    // Clearance pocket for opposite lid knuckle through base rear wall",
        f"    translate([{inner_x-0.3},hy,hz]) rotate([0,90,0]) "
        f"cylinder(h={inner_len+0.6},r={hinge_r+p.pin_radial_clearance_mm});",
        "    // Through-bore including relief outside the short segments",
        f"    for (x=[{margin-0.2},{right_x-0.2}]) "
        f"translate([x,hy,hz]) rotate([0,90,0]) "
        f"cylinder(h={left_span+0.4},d=bore);",
        "  }",
        "}",
        "base_shell();",
        "",
    ]
    lid=header("lid / display tray (down-facing open pocket at closed angle)")
    zbottom=hb+gap
    lid += [
        "module lid_shell() {",
        "  difference() {",
        "    union() {",
        "      difference() {",
        f"        translate([0,0,{zbottom}]) cube([W,D,HLID]);",
        f"        translate([wall,wall,{zbottom-0.1}]) "
        f"cube([W-2*wall,D-2*wall,HLID-floor+0.1]);",
        "      }",
        f"      translate([{inner_x},hy,hz]) rotate([0,90,0]) "
        f"cylinder(h={inner_len},r=kr);",
        "    }",
        "    // Lid-side four-wire cable entry (opposed to left-side base slot)",
        f"    translate([{cable_x},{d-wall-0.1},{zbottom-0.1}]) "
        f"cube([{p.cable_slot_w_mm},{wall+0.2},{p.cable_slot_h_mm+0.2}]);",
        "    // Relief for two base knuckles entering lid rear wall at all open angles",
        f"    for (x=[{margin-0.3},{right_x-0.3}]) "
        f"translate([x,hy,hz]) rotate([0,90,0]) "
        f"cylinder(h={left_span+0.6},r={hinge_r+p.pin_radial_clearance_mm});",
        f"    translate([{inner_x-0.2},hy,hz]) rotate([0,90,0]) "
        f"cylinder(h={inner_len+0.4},d=bore);",
        "  }",
        "}",
        "lid_shell();",
        "",
    ]
    # Need path-relative use directives, NOT duplicate geometry as unrelated viewer.
    # The modeled hinge pin is intentionally metal; no fake proof of bearing strength.
    preview=[
        "// Mecha-Splicer assembly preview only. Angle 0=closed; -135=open.",
        "use <base_shell.scad>",
        "use <lid_shell.scad>",
        f"angle_deg = {p.preview_open_angle_deg};",
        f"hy={hinge_y}; hz={hinge_z};",
        "color([0.17,0.23,0.31]) base_shell();",
        "color([0.42,0.53,0.61])",
        "translate([0,hy,hz]) rotate([angle_deg,0,0])",
        "  translate([0,-hy,-hz]) lid_shell();",
        "",
    ]
    return {
        "base_shell.scad":"\n".join(base),
        "lid_shell.scad":"\n".join(lid),
        "clamshell_open_preview.scad":"\n".join(preview),
    }
