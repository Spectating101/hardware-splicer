import { render, screen } from "@testing-library/react";
import { beforeEach, expect, it, vi } from "vitest";
import DesignView, { matchScene, splitGeometryNote } from "./DesignView.jsx";
import { fetchSceneManifest, fetchSceneRecords, fetchScenes } from "../api.js";

vi.mock("../api.js", () => ({ fetchScenes: vi.fn(), fetchSceneManifest: vi.fn(), fetchSceneRecords: vi.fn() }));
vi.mock("../components/FieldDeckScene.jsx", () => ({
  default: ({ projectId, manifest, embedded }) => <div data-testid="scene" data-project={projectId}
    data-embedded={String(embedded)}>{manifest.title}</div>,
}));

const scenes = [
  { project_id: "cyberdeck-real-trial-20261020", title: "Fielddeck display swap", geometry_status: "available",
    revisions: ["7", "5"], registered_cases: ["fielddeck-7", "fielddeck-5"] },
  { project_id: "drone-build", title: "Holybro X500 V2 frame", geometry_status: "unavailable", revisions: ["v1"], registered_cases: [] },
];
const drone = {
  schema: "hardware_splicer.scene_manifest.v1", project_id: "drone-build", title: "Holybro X500 V2 frame",
  subtitle: "manufacturer reference-frame CAD", geometry_status: "unavailable", geometry_label: "Frame",
  geometry_note: "downloaded_and_hash_identified_not_geometrically_validated\nImport source STEP into a working CAD kernel.",
  revisions: [{ id: "v1", label: "ISO 10303-21 STEP AP214", glb: null, parts: null }],
  sources: [{ label: "Manufacturer 3D CAD File: x500v2-frame.step", href: "https://example.invalid/x500", sha256: "e7cc" },
    { label: "geometry-source.json", path: "projects/drone-build/geometry-source.json" }],
};

beforeEach(() => {
  vi.resetAllMocks();
  fetchScenes.mockResolvedValue(scenes);
});

it("links by project id or a declared registered case, never by a similar name", () => {
  expect(matchScene(scenes, { projectId: "drone-build" })).toMatchObject({ via: "project id" });
  expect(matchScene(scenes, { projectId: "digital-1", caseId: "fielddeck-5" }))
    .toMatchObject({ scene: { project_id: "cyberdeck-real-trial-20261020" }, via: "registered case fielddeck-5" });
  expect(matchScene(scenes, { projectId: "Fielddeck display swap", caseId: "fielddeck" })).toBeNull();
  expect(matchScene(scenes, { projectId: "digital-2", caseId: "hs3g-b" })).toBeNull();
});

it("splits the geometry note into status and next action verbatim", () => {
  expect(splitGeometryNote(drone.geometry_note)).toEqual({
    status: "downloaded_and_hash_identified_not_geometrically_validated", next: "Import source STEP into a working CAD kernel.",
  });
});

it("says not linked and names what would link the project", async () => {
  render(<DesignView projectId="digital-9" caseId="hs3g-b" revision={2} />);
  expect(await screen.findByText("Design view · not linked")).toBeInTheDocument();
  expect(screen.getByText(/would link this project/)).toHaveTextContent("hs3g-b");
  expect(fetchSceneManifest).not.toHaveBeenCalled();
});

it("embeds the linked scene with its own manifest and says it is not this revision's output", async () => {
  fetchSceneManifest.mockResolvedValue({ ...drone, project_id: "cyberdeck-real-trial-20261020", title: "Fielddeck display swap",
    geometry_status: "available", revisions: [{ id: "7", glb: "a.glb", parts: "a.json" }, { id: "5", glb: "b.glb", parts: "b.json" }] });
  render(<DesignView projectId="digital-1" caseId="fielddeck-5" revision={3} />);
  const scene = await screen.findByTestId("scene");
  expect(scene).toHaveAttribute("data-project", "cyberdeck-real-trial-20261020");
  expect(scene).toHaveAttribute("data-embedded", "true");
  expect(screen.getByText(/not generated by revision 3 of this project/)).toBeInTheDocument();
});

it("shows the unavailable geometry as records, with no stage or placeholder", async () => {
  fetchSceneManifest.mockResolvedValue(drone);
  fetchSceneRecords.mockResolvedValue({ records: [{ label: "geometry-source.json", path: "projects/drone-build/geometry-source.json",
    status: "read", data: { device: "Holybro X500 V2 frame", cad_kernel_available: false, licensing_review_completed: false } }] });
  const { container } = render(<DesignView projectId="drone-build" revision={1} />);
  expect(await screen.findByRole("heading", {
    name: "Frame geometry unavailable · downloaded_and_hash_identified_not_geometrically_validated",
  })).toBeInTheDocument();
  expect(screen.getByText("e7cc")).toBeInTheDocument();
  expect(screen.getByRole("link", { name: "Manufacturer 3D CAD File: x500v2-frame.step" })).toBeInTheDocument();
  expect(screen.getByText("Import source STEP into a working CAD kernel.")).toBeInTheDocument();
  expect(await screen.findByText("cad_kernel_available", { selector: "code" })).toBeInTheDocument();
  expect(screen.getByText("licensing_review_completed", { selector: "code" })).toBeInTheDocument();
  expect(screen.queryByTestId("scene")).toBeNull();
  expect(container.querySelector("canvas, .fd-stage")).toBeNull();
});
